SWIFT_EXT = (".swift",)
OBJC_EXT = (".m", ".mm", ".h")
CS_EXT = (".cs", ".xaml", ".csproj")
CPP_EXT = (".c", ".cc", ".cpp", ".cxx", ".h", ".hpp", ".hh")
QT_EXT = CPP_EXT + (".qml", ".pro", ".pri")
DART_EXT = (".dart", ".yaml")
RUST_EXT = (".rs", ".json", ".toml")


@dataclass(frozen=True)
class Rule:
    id: str
    severity: str
    extensions: tuple
    pattern: str
    title: str
    fix: str
    shimmed: bool = False
    flags: int = 0
    _compiled: re.Pattern = field(default=None, compare=False, repr=False)

    def regex(self) -> re.Pattern:
        if self._compiled is None:
            object.__setattr__(self, "_compiled", re.compile(self.pattern, self.flags))
        return self._compiled


def _r(*args, **kwargs) -> Rule:
    return Rule(*args, **kwargs)


