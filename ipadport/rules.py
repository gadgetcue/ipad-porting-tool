"""Compatibility rules: source patterns that behave differently (or not at all) on iPadOS / iOS.

Each rule has a severity:

* ``blocker``  - there is no iOS equivalent; the feature must be removed or redesigned.
* ``major``    - needs a real code change (different API, different UI pattern).
* ``minor``    - small change, or handled automatically by the generated iPad project.
* ``info``     - worth knowing, no action required in most apps.

``shimmed=True`` means the project generated by ``ipadport port`` provides a working
replacement, so the code keeps working without changes (within the limits described
in the rule's ``fix`` text).
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

SEVERITIES = ("blocker", "major", "minor", "info")

