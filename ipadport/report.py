"""Render scan reports as text, Markdown or JSON."""

from __future__ import annotations

import json

from .guides import guide_for
from .rules import RULES_BY_ID
from .scan import Report

ICONS = {"blocker": "BLOCKER", "major": "MAJOR", "minor": "minor", "info": "info"}
MAX_LOCATIONS = 5


def to_json(report: Report) -> str:
    return json.dumps(report.to_dict(), indent=2)


def to_text(report: Report) -> str:
    lines = []
    p = report.primary
    lines.append(f"ipadport analysis: {report.name}")
    lines.append("=" * len(lines[0]))
    if p:
        lines.append(f"Detected:  {p.label}  (strategy: {p.strategy})")
        for other in report.detections[1:]:
            lines.append(f"Also:      {other.label}")
    else:
        lines.append("Detected:  nothing recognisable")
    c = report.counts()
    lines.append(f"Score:     {report.score()}/100  ({c['blocker']} blockers, {c['major']} major, "
                 f"{c['minor']} minor, {c['info']} info)")
    lines.append(f"Verdict:   {report.verdict()}")
    lines.append(f"Scanned:   {report.files_scanned} files")
    lines.append("")
    for rule_id, items in report.by_rule().items():
        rule = items[0].rule
        tag = ICONS[rule.severity] + (" (auto-handled)" if rule.shimmed else "")
        lines.append(f"[{tag}] {rule.title}  x{len(items)}")
        for f in items[:MAX_LOCATIONS]:
            lines.append(f"    {f.file}:{f.line}  {f.snippet}")
        if len(items) > MAX_LOCATIONS:
            lines.append(f"    ... and {len(items) - MAX_LOCATIONS} more")
        lines.append(f"    -> {rule.fix}")
        lines.append("")
    if report.ipc_channels:
        lines.append(f"Electron IPC channels to port: {', '.join(sorted(report.ipc_channels))}")
        lines.append("")
    if p:
        guide = guide_for(p.kind)
        lines.append("Next steps:")
        for i, step in enumerate(guide["steps"], 1):
            lines.append(f"  {i}. {step}")
    return "\n".join(lines).rstrip() + "\n"


def to_markdown(report: Report, title: str | None = None) -> str:
    p = report.primary
    c = report.counts()
    out = [f"# {title or 'Porting plan: ' + report.name}", ""]
    out.append("Generated by [ipadport](https://github.com/gadgetcue/ipad-porting-tool).")
    out.append("")
    out.append("| | |")
    out.append("|---|---|")
    out.append(f"| Project type | {p.label if p else 'unknown'} |")
    out.append(f"| Strategy | `{p.strategy if p else '-'}` |")
    out.append(f"| Portability score | **{report.score()}/100** |")
    out.append(f"| Issues | {c['blocker']} blockers, {c['major']} major, {c['minor']} minor, {c['info']} info |")
    out.append(f"| Verdict | {report.verdict()} |")
    out.append("")
    if p:
        guide = guide_for(p.kind)
        out.append("## How this app is ported")
        out.append("")
        out.append(guide["summary"])
        out.append("")
        for i, step in enumerate(guide["steps"], 1):
            out.append(f"{i}. {step}")
        out.append("")

    if report.ipc_channels:
        out.append("## Electron IPC channels to port")
        out.append("")
        out.append("Each channel below was handled by the Electron main process. Implement it in "
                   "`ipc-handlers.js` (a stub has been generated for each one).")
        out.append("")
        out.append("| Channel | Defined in | Used in |")
        out.append("|---|---|---|")
        for name in sorted(report.ipc_channels):
            entry = report.ipc_channels[name]
            out.append(f"| `{name}` | {', '.join(entry['defined_in']) or '(not found)'} | "
                       f"{', '.join(entry['used_in'][:3]) or '-'} |")
        out.append("")

    groups = [("blocker", "Blockers: no iOS equivalent"), ("major", "Major: needs code changes"),
              ("minor", "Minor: small changes or handled automatically"), ("info", "Info")]
    by_rule = report.by_rule()
    for severity, heading in groups:
        rules = [(rid, items) for rid, items in by_rule.items() if RULES_BY_ID[rid].severity == severity]
        if not rules:
            continue
        out.append(f"## {heading}")
        out.append("")
        for rid, items in rules:
            rule = RULES_BY_ID[rid]
            done = " (handled by the generated project)" if rule.shimmed else ""
            out.append(f"### {rule.title}{done}")
            out.append("")
            out.append(rule.fix)
            out.append("")
            for f in items[:MAX_LOCATIONS * 2]:
                out.append(f"- [ ] `{f.file}:{f.line}`: `{f.snippet.replace('`', chr(39))}`")
            if len(items) > MAX_LOCATIONS * 2:
                out.append(f"- ... and {len(items) - MAX_LOCATIONS * 2} more")
            out.append("")
    if not by_rule:
        out.append("No compatibility issues were found by the scanner. Test every feature on a device anyway: "
                   "the scanner recognises common APIs, not every possible desktop dependency.")
        out.append("")
    out.append("## Always test")
    out.append("")
    out.append("- iPhone portrait and landscape, iPad full screen, Split View and Slide Over, Stage Manager.")
    out.append("- Touch only (no keyboard), then with a hardware keyboard and trackpad.")
    out.append("- Dark mode, Dynamic Type sizes, and the app being suspended and resumed.")
    out.append("")
    return "\n".join(out)
