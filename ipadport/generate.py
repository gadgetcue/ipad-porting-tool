"""Generate an iPad / iPhone project from a scanned desktop project."""

from __future__ import annotations

import json
import os
import re
import shutil
import struct
from dataclasses import dataclass
from pathlib import Path

from . import __version__
from .detect import (NATIVE_TOOLCHAIN, REWRITE_UI, SWIFT_MULTIPLATFORM, WEB_WRAPPER, find_web_root,
                     needs_build, project_version)
from .report import to_markdown
from .scan import Report

TEMPLATES = Path(__file__).parent / "templates"
COPY_IGNORE = shutil.ignore_patterns("node_modules", ".git", ".DS_Store", "*.map.gz", "ipad-port", ".cache")


class GenerateError(Exception):
    pass


@dataclass
class Options:
    out: Path
    name: str | None = None
    bundle_id: str | None = None
    team_id: str = ""
    web_root: Path | None = None
    entry: str | None = None
    remote_url: str | None = None
    viewport: str = "device"          # device | desktop | keep | force
    content_mode: str = "recommended"  # recommended | mobile | desktop
    edge_to_edge: bool = False
    inspectable: bool = True
    allow_unbuilt: bool = False
    force: bool = False
    deployment_target: str = "16.0"


def _identifier(name: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", name)
    ident = "".join(w[:1].upper() + w[1:] for w in words) or "Ported"
    if ident[0].isdigit():
        ident = "App" + ident
    return ident


def _bundle_suffix(name: str) -> str:
    s = re.sub(r"[^a-z0-9]", "", name.lower())
    return s or "portedapp"


def _yaml_str(value: str) -> str:
    return json.dumps(value)  # JSON strings are valid YAML double-quoted scalars


def _png_size(path: Path) -> tuple[int, int] | None:
    try:
        with open(path, "rb") as fh:
            head = fh.read(24)
    except OSError:
        return None
    if len(head) < 24 or head[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    return struct.unpack(">II", head[16:24])


def find_icon(root: Path) -> Path | None:
    candidates = ["build/icon.png", "icon.png", "assets/icon.png", "resources/icon.png", "public/icon.png",
                  "src-tauri/icons/icon.png", "static/icon.png", "icons/icon.png", "build/icons/1024x1024.png",
                  "public/icon-1024.png", "assets/icon-1024.png"]
    for rel in candidates:
        p = root / rel
        if p.is_file() and _png_size(p) == (1024, 1024):
            return p
    return None


def _prepare_out(out: Path, force: bool) -> None:
    if out.exists() and any(out.iterdir()):
        marker = out / ".ipadport"
        if not (force or marker.exists()):
            raise GenerateError(f"{out} is not empty. Use --force to overwrite it.")
        for child in out.iterdir():
            if child.name in ("build", "DerivedData"):
                continue
            if child.is_dir() and not child.is_symlink():
                shutil.rmtree(child)
            else:
                child.unlink()
    out.mkdir(parents=True, exist_ok=True)
    (out / "Support").mkdir(exist_ok=True)
    (out / ".ipadport").write_text(f"Generated by ipadport {__version__}. Re-running `ipadport port` replaces this folder.\n")


def generate(root: Path, report: Report, opts: Options) -> dict:
    """Generate the port. Returns a summary dict (files written, next steps)."""
    root = Path(root).resolve()
    out = Path(opts.out).resolve()
    if out == root:
        raise GenerateError("The output folder must be different from the project folder.")
    primary = report.primary
    if primary is None and not opts.remote_url and not opts.web_root:
        raise GenerateError("Could not recognise the project type. Point ipadport at the app's source folder, "
                            "or pass --web-root for a web app.")
    strategy = primary.strategy if primary else WEB_WRAPPER
    if opts.web_root or opts.remote_url:
        strategy = WEB_WRAPPER

    if strategy == WEB_WRAPPER:
        return _generate_web(root, report, opts, out)
    _prepare_out(out, opts.force)
    if strategy == SWIFT_MULTIPLATFORM:
        return _generate_swift(root, report, opts, out)
    # Toolchain / rewrite strategies: the right tool is the framework's own; write the plan.
    (out / "PORTING_PLAN.md").write_text(to_markdown(report))
    return {"strategy": strategy, "out": str(out), "files": ["PORTING_PLAN.md"],
            "message": ("This framework can target iOS with its own tooling; follow PORTING_PLAN.md."
                        if strategy == NATIVE_TOOLCHAIN else
                        "The desktop UI must be rebuilt for touch; PORTING_PLAN.md lists what to keep and what to replace.")}


# ------------------------------------------------------------------------------------------ web wrapper

def _ipc_handlers_js(report: Report) -> str:
    lines = [
        "/*",
        " * ipadport: Electron main-process IPC handlers, re-implemented for iPad / iPhone.",
        " *",
        " * The Electron main process (Node.js) does not exist on iOS. Every ipcRenderer.invoke/send/sendSync",
        " * call from your renderer or preload is routed to the function with the same channel name below.",
        " * Return a value (or a Promise) exactly like your ipcMain.handle handler did. `this.event` is a",
        " * stand-in for the Electron event object. To push events to the renderer (webContents.send), call",
        " * ipadport.send(channel, ...args).",
        " *",
        " * Available native APIs: ipadport.fs (Node-like, sandboxed), ipadport.store, ipadport.dialog,",
        " * ipadport.clipboard, ipadport.share, ipadport.openExternal, ipadport.notify, ipadport.path.",
        " *",
        " * Keep your edits: copy this file to `ipadport/ipc-handlers.js` in your project. ipadport will use it",
        " * instead of regenerating stubs.",
        " */",
        "(function () {",
        "  'use strict';",
        "  var ipadport = window.ipadport;",
        "  var fs = ipadport.fs, path = ipadport.path, store = ipadport.store;",
        "",
        "  window.ipadportHandlers = Object.assign(window.ipadportHandlers || {}, {",
    ]
    for name in sorted(report.ipc_channels):
        entry = report.ipc_channels[name]
        where = ", ".join(entry["defined_in"]) or "no ipcMain handler found"
        lines.append(f"    // {name}  (original: {where})")
        source = entry.get("source")
        if source:
            for src_line in source.splitlines()[:25]:
                lines.append(f"    //   {src_line}")
        lines.append(f"    {json.dumps(name)}: function () {{")
        lines.append(f"      throw new Error({json.dumps('IPC channel ' + chr(34) + name + chr(34) + ' is not ported yet: implement it in ipc-handlers.js')});")
        lines.append("    },")
        lines.append("")
    lines += ["  });", "})();", ""]
    return "\n".join(lines)


def _wrap_preload(source: str) -> str:
    return (
        "/* Electron preload script, run by ipadport with a require() that provides electron/fs/path/os shims. */\n"
        "(function (require, module, exports, process, __dirname, __filename) {\n"
        + source
        + "\n})(window.ipadport.require, { exports: {} }, {}, window.process, '/', '/preload.js');\n"
    )


def _render(template: str, values: dict) -> str:
    for key, value in values.items():
        template = template.replace(f"__{key}__", value)
    return template


def _generate_web(root: Path, report: Report, opts: Options, out: Path) -> dict:
    primary = report.primary
    kind = primary.kind if primary else "web"
    details = primary.details if primary else {}
    warnings: list[str] = []

    web_root, entry, preload = (None, opts.entry or "index.html", None)
    if not opts.remote_url:
        if opts.web_root:
            web_root = Path(opts.web_root).resolve()
            entry = opts.entry or "index.html"
            if kind == "electron":
                _, _, preload = find_web_root(root, kind, details)
        else:
            web_root, entry, preload = find_web_root(root, kind, details)
            entry = opts.entry or entry
        if web_root is None or not (web_root / entry).is_file():
            raise GenerateError(
                "Could not find the app's built HTML (looked in dist/, build/, out/, www/, public/, src/ and the "
                "Electron main file). Build the app first (e.g. `npm run build`) or pass --web-root <folder>.")
        if needs_build(root, web_root) and not opts.allow_unbuilt:
            raise GenerateError(
                f"{web_root / entry} loads source files (e.g. /src/main.tsx) that need a bundler. Run your build "
                "(e.g. `npm run build`) and try again, or pass --web-root pointing at the build output.")
        if out == web_root or out in web_root.parents or (web_root in out.parents and out.parent != web_root):
            raise GenerateError("The output folder must not contain, or be nested deep inside, the web content folder.")

    _prepare_out(out, opts.force)
    name = opts.name or report.name
    target = _identifier(name)
    bundle_id = opts.bundle_id or f"com.example.{_bundle_suffix(name)}"
    version = project_version(root)

    # Sources
    src_out = out / "Sources"
    src_out.mkdir()
    values = {
        "APP_STRUCT": target + "App",
        "ENTRY": entry.replace("\\", "/"),
        "REMOTE_URL": json.dumps(opts.remote_url) if opts.remote_url else "nil",
        "CONTENT_MODE": opts.content_mode,
        "EDGE_TO_EDGE": "true" if opts.edge_to_edge else "false",
        "INSPECTABLE": "true" if opts.inspectable else "false",
        "IPADPORT_VERSION": __version__,
    }
    for tpl in sorted((TEMPLATES / "web" / "Sources").glob("*.swift")):
        (src_out / tpl.name).write_text(_render(tpl.read_text(), values))

    # Bundle resources (JS)
    res_out = out / "BundleResources"
    res_out.mkdir()
    has_node_integration = any(f.rule.id == "electron-node-integration" for f in report.findings)
    config = {
        "electron": kind == "electron",
        "nodeRequire": kind == "electron" and has_node_integration,
        "viewport": opts.viewport,
        "appName": name,
        "appVersion": version,
    }
    shim = _render((TEMPLATES / "web" / "BundleResources" / "ipadport-shim.js").read_text(), values)
    (res_out / "ipadport-shim.js").write_text(
        f"window.__IPADPORT_CONFIG__ = {json.dumps(config)};\n" + shim)
    files = ["Sources/*.swift", "BundleResources/ipadport-shim.js"]

    if kind == "electron":
        custom = root / "ipadport" / "ipc-handlers.js"
        if custom.is_file():
            shutil.copyfile(custom, res_out / "ipc-handlers.js")
        else:
            (res_out / "ipc-handlers.js").write_text(_ipc_handlers_js(report))
            if report.ipc_channels:
                warnings.append(f"{len(report.ipc_channels)} Electron IPC channel(s) need porting in "
                                "BundleResources/ipc-handlers.js (they throw a clear error until then).")
        files.append("BundleResources/ipc-handlers.js")
        if preload is not None:
            source = preload.read_text(encoding="utf-8", errors="replace")
            if re.search(r"^\s*(import|export)\s", source, re.M):
                warnings.append(f"Preload {preload.name} is an ES module; bundle it to a single CommonJS file "
                                "(e.g. with esbuild) and re-run, or port it into ipc-handlers.js.")
            if re.search(r"require\(\s*['\"]\.{1,2}/", source):
                warnings.append(f"Preload {preload.name} requires local files; bundle it into one file first.")
            (res_out / "preload.js").write_text(_wrap_preload(source))
            files.append("BundleResources/preload.js")

    # Web content
    if web_root is not None:
        ignore_out = shutil.ignore_patterns(out.name) if out.parent == web_root else None

        def _ignore(directory, names):
            skipped = set(COPY_IGNORE(directory, names))
            if ignore_out:
                skipped |= set(ignore_out(directory, names))
            return skipped

        shutil.copytree(web_root, out / "web", ignore=_ignore)
        files.append("web/ (copied from " + os.path.relpath(web_root, root) + ")")
    else:
        (out / "web").mkdir()
        (out / "web" / "index.html").write_text("<!doctype html><title>Loading</title>")

    # App icon
    icon = find_icon(root)
    if icon:
        icon_dir = out / "Assets.xcassets" / "AppIcon.appiconset"
        icon_dir.mkdir(parents=True)
        shutil.copyfile(icon, icon_dir / "icon.png")
        (out / "Assets.xcassets" / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}))
        (icon_dir / "Contents.json").write_text(json.dumps({
            "images": [{"filename": "icon.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"}],
            "info": {"author": "xcode", "version": 1}}, indent=2))
        files.append("Assets.xcassets (app icon from " + os.path.relpath(icon, root) + ")")
    else:
        warnings.append("No 1024x1024 PNG icon found; add one to the project (Assets.xcassets/AppIcon) before release.")

    (out / "project.yml").write_text(_project_yml(target, name, bundle_id, version, opts, has_icon=bool(icon),
                                                  web_sources=True))
    (out / "PORTING_PLAN.md").write_text(to_markdown(report))
    (out / "README.md").write_text(_out_readme(target, name, warnings))
    files += ["project.yml", "PORTING_PLAN.md", "README.md"]
    return {"strategy": WEB_WRAPPER, "out": str(out), "files": files, "warnings": warnings, "target": target,
            "message": f"Generated an adaptive iPad/iPhone app project '{target}'."}


def _project_yml(target: str, display: str, bundle_id: str, version: str, opts: Options, has_icon: bool,
                 web_sources: bool, extra_sources: list | None = None) -> str:
    lines = [
        f"# Generated by ipadport {__version__}. Create the Xcode project with:  xcodegen generate",
        f"name: {target}",
        "options:",
        "  createIntermediateGroups: true",
        "  deploymentTarget:",
        f"    iOS: {_yaml_str(opts.deployment_target)}",
        "settings:",
        "  base:",
        '    SWIFT_VERSION: "5.0"',
        f"    MARKETING_VERSION: {_yaml_str(version)}",
        '    CURRENT_PROJECT_VERSION: "1"',
        "targets:",
        f"  {target}:",
        "    type: application",
        "    platform: iOS",
        "    sources:",
    ]
    if web_sources:
        lines += [
            "      - path: Sources",
            "      - path: BundleResources",
            "        buildPhase: resources",
            "      - path: web",
            "        type: folder",
            "        buildPhase: resources",
        ]
    for src in extra_sources or []:
        lines += [f"      - path: {_yaml_str(src['path'])}"]
        if src.get("excludes"):
            lines.append("        excludes:")
            lines += [f"          - {_yaml_str(e)}" for e in src["excludes"]]
    if has_icon:
        lines += ["      - path: Assets.xcassets"]
    orientations = ["UIInterfaceOrientationPortrait", "UIInterfaceOrientationPortraitUpsideDown",
                    "UIInterfaceOrientationLandscapeLeft", "UIInterfaceOrientationLandscapeRight"]
    lines += [
        "    info:",
        "      path: Support/Info.plist",
        "      properties:",
        f"        CFBundleDisplayName: {_yaml_str(display)}",
        "        CFBundleShortVersionString: $(MARKETING_VERSION)",
        "        CFBundleVersion: $(CURRENT_PROJECT_VERSION)",
        "        UILaunchScreen: {}",
        "        UIApplicationSceneManifest:",
        "          UIApplicationSupportsMultipleScenes: true",
        "        UIRequiresFullScreen: false",
        "        UIFileSharingEnabled: true",
        "        LSSupportsOpeningDocumentsInPlace: true",
        "        ITSAppUsesNonExemptEncryption: false",
        "        UISupportedInterfaceOrientations:",
    ]
    lines += [f"          - {o}" for o in orientations if "UpsideDown" not in o]
    lines += ["        UISupportedInterfaceOrientations~ipad:"]
    lines += [f"          - {o}" for o in orientations]
    lines += [
        "    settings:",
        "      base:",
        f"        PRODUCT_BUNDLE_IDENTIFIER: {_yaml_str(bundle_id)}",
        '        TARGETED_DEVICE_FAMILY: "1,2"',
        "        CODE_SIGN_STYLE: Automatic",
        f"        DEVELOPMENT_TEAM: {_yaml_str(opts.team_id)}",
        '        SUPPORTS_MACCATALYST: "NO"',
        '        ENABLE_PREVIEWS: "YES"',
    ]
    if has_icon:
        lines.append("        ASSETCATALOG_COMPILER_APPICON_NAME: AppIcon")
    lines += [
        "    scheme: {}",
        "",
    ]
    return "\n".join(lines)


def _out_readme(target: str, name: str, warnings: list) -> str:
    out = [
        f"# {name} for iPad and iPhone",
        "",
        "Generated by [ipadport](https://github.com/gadgetcue/ipad-porting-tool).",
        "",
        "## Build",
        "",
        "On a Mac with Xcode 15 or newer:",
        "",
        "```sh",
        "brew install xcodegen",
        "xcodegen generate",
        f"open {target}.xcodeproj",
        "```",
        "",
        "Select your team under *Signing & Capabilities*, pick an iPad or iPhone simulator and press Run.",
        "",
        "## Layout of this folder",
        "",
        "- `web/`: your app's HTML/CSS/JS, served to the web view from `app://local/`.",
        "- `Sources/`: the native shell (SwiftUI + WKWebView) and the native bridge.",
        "- `BundleResources/ipadport-shim.js`: `window.ipadport` APIs and Electron compatibility.",
        "- `BundleResources/ipc-handlers.js`: Electron main-process handlers to port (Electron apps).",
        "- `PORTING_PLAN.md`: everything the scanner found, with fixes.",
        "",
        "## Adaptive layout hooks for your CSS / JS",
        "",
        "- `<html>` gets `ipadport-compact` or `ipadport-regular` (horizontal size class) and `ipadport-pad` /",
        "  `ipadport-phone`; they update live in Split View and Stage Manager.",
        "- `window.addEventListener('ipadport:sizeclass', e => ...)` fires on changes.",
        "- CSS variables `--ipadport-safe-top/right/bottom/left` expose the safe-area insets.",
        "",
    ]
    if warnings:
        out += ["## Things to do", ""] + [f"- {w}" for w in warnings] + [""]
    return "\n".join(out)


# ------------------------------------------------------------------------------------------ Swift

def _generate_swift(root: Path, report: Report, opts: Options, out: Path) -> dict:
    name = opts.name or report.name
    target = _identifier(name) + "iOS"
    bundle_id = opts.bundle_id or f"com.example.{_bundle_suffix(name)}.ios"
    shutil.copyfile(TEMPLATES / "swift" / "PlatformCompat.swift", out / "PlatformCompat.swift")

    # Find the folders that hold the app's Swift sources (skip tests, packages' build dirs).
    source_dirs: set = set()
    for path in root.rglob("*.swift"):
        if out == path or out in path.parents:
            continue
        rel = path.relative_to(root)
        parts = rel.parts
        if any(p in (".build", "DerivedData", "Pods", "build", ".git") or p.endswith("Tests") or p.endswith("UITests")
               for p in parts):
            continue
        if path.name == "Package.swift":
            continue
        source_dirs.add(parts[0] if len(parts) > 1 else ".")
    rel_root = os.path.relpath(root, out)
    extra = []
    for d in sorted(source_dirs):
        src_path = rel_root if d == "." else os.path.join(rel_root, d)
        extra.append({"path": src_path, "excludes": ["**/*Tests*", "**/*.xcodeproj", "**/Package.swift",
                                                     "**/Info.plist", "**/*.entitlements", "**/Preview Content"]})
    extra.append({"path": "PlatformCompat.swift"})
    (out / "project.yml").write_text(_project_yml(target, name, bundle_id, project_version(root), opts,
                                                  has_icon=False, web_sources=False, extra_sources=extra))
    (out / "PORTING_PLAN.md").write_text(to_markdown(report))
    return {"strategy": SWIFT_MULTIPLATFORM, "out": str(out),
            "files": ["project.yml", "PlatformCompat.swift", "PORTING_PLAN.md"], "target": target,
            "message": f"Generated an iOS target '{target}' that compiles your Swift sources. Build it and fix the "
                       "AppKit-specific code listed in PORTING_PLAN.md."}
